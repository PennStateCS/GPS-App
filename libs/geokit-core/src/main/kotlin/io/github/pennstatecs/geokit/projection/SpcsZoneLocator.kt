package io.github.pennstatecs.geokit.projection

/** What a [SpcsZoneSuggestion] is based on. */
public enum class SpcsZoneBasis {
    /**
     * The point lies inside the zone's legal extent, built from the counties that define it (Census
     * 1:20,000,000 cartographic county lines). Reliable away from county lines; within a few hundred
     * metres of a zone boundary the generalised lines can put a point on the wrong side.
     */
    COUNTY_BOUNDARY,

    /**
     * No county-defined zone contains the point (Alaska, offshore, or just outside the generalised
     * coastline), so the zone comes from EPSG area-of-use bounding boxes. Boxes of neighbouring zones
     * overlap: treat the result as a guess.
     */
    AREA_OF_USE_BOX,

    /** No zone of the set covers the point. */
    NONE,
}

/**
 * A State Plane zone suggestion for a position. Always a suggestion: the user chooses the zone.
 * @property suggested the zone to propose, or null when [basis] is [SpcsZoneBasis.NONE].
 * @property candidates every zone matching the point on the same [basis], [suggested] first. More than
 *   one means an ambiguity to show the user (e.g. Kentucky North/South vs Kentucky Single Zone, which
 *   are both legal, or overlapping area-of-use boxes).
 * @property basis what the suggestion rests on.
 */
public data class SpcsZoneSuggestion(
    public val suggested: SpcsZone?,
    public val candidates: List<SpcsZone>,
    public val basis: SpcsZoneBasis,
) {
    /** True when more than one zone matches the point. */
    public val isAmbiguous: Boolean get() = candidates.size > 1
}

/**
 * A family of State Plane zones together with the polygons of their legal extents.
 *
 * Today there is one set, [SPCS83]: the 118 zones of [SpcsZones] and the county-defined extents
 * generated by `libs/geokit-core/tools/coords/gen_spcs_boundaries.py` into the classpath resource
 * [SPCS83_BOUNDARY_RESOURCE]. Zones without polygons (Alaska, defined by meridians and parallels) are
 * located by their EPSG area-of-use box.
 *
 * **SPCS2022.** The State Plane Coordinate System of 2022 (on NATRF2022) has new and layered zones
 * (statewide plus regional zones that overlap legally). It plugs in as a second set without
 * restructuring: a generated zone table (like `SpcsZoneTable`), a boundary resource from the NGS SPCS2022
 * zone definitions written in the same format (keys = the zones' [SpcsZone.epsg] codes, or whatever stable
 * code those zones get), and a `SPCS2022` companion value. [SpcsZoneLocator] already reports overlapping
 * zones as [SpcsZoneSuggestion.candidates], which layered zones need.
 */
public class SpcsZoneSet internal constructor(
    /** Display name of the set, e.g. "SPCS83". */
    public val name: String,
    /** All zones of the set. */
    public val zones: List<SpcsZone>,
    boundaryResource: String?,
) {
    internal val boundaries: SpcsZoneBoundaries? by lazy {
        boundaryResource?.let { SpcsZoneBoundaries.fromClasspath(it) }
    }

    /** True if [zone] is located by its county-defined extent (else by its area-of-use box). */
    public fun hasBoundary(zone: SpcsZone): Boolean = boundaries?.keys?.contains(zone.epsg) == true

    public companion object {
        /** Classpath location of the SPCS83 zone polygons bundled in geokit-core's jar (~60 kB). */
        public const val SPCS83_BOUNDARY_RESOURCE: String = "spcs/spcs83_zones.bin"

        /** The official SPCS83 zones on NAD83(2011) ([SpcsZones.all]). */
        public val SPCS83: SpcsZoneSet by lazy { SpcsZoneSet("SPCS83", SpcsZones.all, SPCS83_BOUNDARY_RESOURCE) }
    }
}

/**
 * Suggests the State Plane zone for a position from the zones' legal extents.
 *
 * 1. Zones whose county-defined extent contains the point ([SpcsZoneBasis.COUNTY_BOUNDARY]).
 * 2. Otherwise zones whose EPSG area-of-use box contains it ([SpcsZoneBasis.AREA_OF_USE_BOX]).
 * 3. Otherwise none.
 * Among several matches the zone with the smallest area-of-use box is suggested (e.g. Kentucky North or
 * South before Kentucky Single Zone); all matches are returned as candidates.
 *
 * Input is latitude/longitude in degrees. The extents are NAD83, but WGS84 (a GNSS fix) may be passed:
 * the ~1-2 m datum difference is far below the generalisation of the county lines. Points within a few
 * hundred metres of a zone boundary may be assigned to the neighbouring zone; the result is a suggestion
 * for the user to confirm, never a substitute for choosing the zone of the project.
 *
 * The polygons load lazily on first use (about 60 kB from the classpath); [IllegalStateException] if the
 * resource is missing.
 */
public class SpcsZoneLocator(public val zoneSet: SpcsZoneSet = SpcsZoneSet.SPCS83) {

    /** Suggestion for the point (degrees). */
    public fun locate(latDeg: Double, lonDeg: Double): SpcsZoneSuggestion {
        if (!latDeg.isFinite() || !lonDeg.isFinite()) return SpcsZoneSuggestion(null, emptyList(), SpcsZoneBasis.NONE)
        val b = zoneSet.boundaries
        if (b != null) {
            val hits = zoneSet.zones.filter { b.contains(it.epsg, latDeg, lonDeg) }.sortedBy { it.areaDeg2 }
            if (hits.isNotEmpty()) return SpcsZoneSuggestion(hits.first(), hits, SpcsZoneBasis.COUNTY_BOUNDARY)
        }
        val boxes = zoneSet.zones.filter { it.contains(latDeg, lonDeg) }.sortedBy { it.areaDeg2 }
        return if (boxes.isEmpty()) SpcsZoneSuggestion(null, emptyList(), SpcsZoneBasis.NONE)
        else SpcsZoneSuggestion(boxes.first(), boxes, SpcsZoneBasis.AREA_OF_USE_BOX)
    }

    public companion object {
        /** Locator over [SpcsZoneSet.SPCS83]. */
        public val SPCS83: SpcsZoneLocator by lazy { SpcsZoneLocator(SpcsZoneSet.SPCS83) }
    }
}
