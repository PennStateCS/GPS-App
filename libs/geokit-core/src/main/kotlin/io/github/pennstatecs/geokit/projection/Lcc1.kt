package io.github.pennstatecs.geokit.projection

import io.github.pennstatecs.geokit.ellipsoid.Ellipsoid

import kotlin.math.PI
import kotlin.math.abs
import kotlin.math.atan
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.pow
import kotlin.math.sign
import kotlin.math.sin
import kotlin.math.sqrt
import kotlin.math.tan

/**
 * Lambert Conic Conformal (1SP), EPSG method 9801 (EPSG Guidance Note 7-2, §3.1.1.1), on GRS80 — the
 * one-parallel form SPCS2022 uses ("LC1"): the latitude of natural origin is the single standard
 * (central) parallel, with scale [k0] on it; false easting/northing are at the natural origin.
 * Works in both hemispheres (American Samoa's zone has a southern origin). Angles in degrees, lengths
 * in metres. Verified against NGS-published SPCS2022 example coordinates and PROJ
 * (test resources under `crs/spcs2022`, generated by `tools/nsrs/gen_spcs2022.py`).
 *
 * @param latOrigin latitude of natural origin (= the standard parallel). @param lonOrigin longitude of
 *   natural origin. @param k0 scale factor at the natural origin. @param fe false easting. @param fn false northing.
 */
public class Lcc1(
    latOrigin: Double,
    private val lonOrigin: Double,
    private val k0: Double,
    private val fe: Double,
    private val fn: Double,
) : SpcsProjection {
    override val method: ProjectionMethod get() = ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP
    override val parameters: Map<String, Double> = linkedMapOf(
        "lat_0" to latOrigin, "lon_0" to lonOrigin, "k_0" to k0, "x_0" to fe, "y_0" to fn,
    )

    private val a = Ellipsoid.GRS80.semiMajorAxisM
    private val e2 = Ellipsoid.GRS80.eccentricitySquared
    private val e = sqrt(e2)
    private val n: Double
    private val aF: Double   // a · F · k0
    private val r0: Double

    init {
        require(latOrigin > -90.0 && latOrigin < 90.0 && latOrigin != 0.0) {
            "Lambert Conic Conformal (1SP): latitude of origin must be within (-90, 90) and not 0 ($latOrigin)"
        }
        require(k0 > 0.0) { "Lambert Conic Conformal (1SP): scale factor must be positive ($k0)" }
        val phi0 = Math.toRadians(latOrigin)
        n = sin(phi0)
        val m0 = cos(phi0) / sqrt(1 - e2 * sin(phi0) * sin(phi0))
        val t0 = t(phi0)
        aF = a * m0 / (n * t0.pow(n)) * k0
        r0 = aF * t0.pow(n)
    }

    private fun t(phi: Double): Double {
        val es = e * sin(phi)
        return tan(PI / 4 - phi / 2) / ((1 - es) / (1 + es)).pow(e / 2)
    }

    /** Latitude/longitude (degrees) → (easting, northing) metres. */
    override fun forward(latDeg: Double, lonDeg: Double): Pair<Double, Double> {
        val r = aF * t(Math.toRadians(latDeg)).pow(n)
        val theta = n * Math.toRadians(lonNear(lonDeg, lonOrigin) - lonOrigin)
        return (fe + r * sin(theta)) to (fn + r0 - r * cos(theta))
    }

    /** Inverse: (easting, northing) metres → (latitude, longitude) degrees; longitude in −180..180. */
    public fun inverse(eastingM: Double, northingM: Double): Pair<Double, Double> {
        val s = sign(n)
        val dx = eastingM - fe
        val dy = r0 - (northingM - fn)
        val r = s * sqrt(dx * dx + dy * dy)
        val theta = atan2(s * dx, s * dy)
        val tp = (r / aF).pow(1 / n)
        var phi = PI / 2 - 2 * atan(tp)
        for (i in 0 until 30) {
            val es = e * sin(phi)
            val next = PI / 2 - 2 * atan(tp * ((1 - es) / (1 + es)).pow(e / 2))
            val done = abs(next - phi) < 1e-15
            phi = next
            if (done) break
        }
        return Math.toDegrees(phi) to wrapLon180(Math.toDegrees(theta / n) + lonOrigin)
    }
}

/** [lonDeg] wrapped into −180..180. */
internal fun wrapLon180(lonDeg: Double): Double {
    var l = lonDeg
    while (l > 180.0) l -= 360.0
    while (l < -180.0) l += 360.0
    return l
}
