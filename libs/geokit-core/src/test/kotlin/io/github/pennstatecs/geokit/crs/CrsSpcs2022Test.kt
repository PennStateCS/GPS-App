/**
 * The SPCS2022 catalog generated by tools/nsrs/gen_spcs2022.py, checked against the raw NGS tables
 * (parameters), NGS's published example coordinates (GeoKit's own maths, forward and inverse) and PROJ
 * (independent implementation, 5 points per zone).
 */
class CrsSpcs2022Test {

    private val dir = "src/test/resources/crs/spcs2022"
    private val load = CrsCatalogCsv.fromClasspath(CrsRegistry.SPCS2022_RESOURCE, CrsCatalogId.SPCS2022)
    private val byCode = load.entries.associateBy { it.zoneCode!! }

    // ---- raw NGS JSON (flat objects of string values) ----

    private fun rawTable(name: String): Map<String, Map<String, String>> {
        val text = GZIPInputStream(File("$dir/raw/$name.gz").inputStream()).use { it.readBytes().toString(Charsets.UTF_8) }
        val obj = Regex("\\{([^{}]*)\\}")
        val kv = Regex("\"((?:[^\"\\\\]|\\\\.)*)\"\\s*:\\s*\"((?:[^\"\\\\]|\\\\.)*)\"")
        fun unescape(s: String) = Regex("\\\\u([0-9a-fA-F]{4})|\\\\(.)").replace(s) { m ->
            m.groups[1]?.let { it.value.toInt(16).toChar().toString() } ?: m.groupValues[2]
        }
        return obj.findAll(text).map { o -> kv.findAll(o.groupValues[1]).associate { unescape(it.groupValues[1]) to unescape(it.groupValues[2]) } }
            .associateBy { it.getValue("Zone code") }
    }

    private fun dms(s: String): Double {
        val m = Regex("^(\\d+)°(\\d+)'(?:([\\d.]+)\")?([NSEW])$").find(s.trim()) ?: error("bad DMS $s")
        val (d, mi, sec, h) = m.destructured
        val v = BigDecimal(d).add(BigDecimal(mi).divide(BigDecimal(60), 30, java.math.RoundingMode.HALF_EVEN))
            .add(if (sec.isEmpty()) BigDecimal.ZERO else BigDecimal(sec).divide(BigDecimal(3600), 30, java.math.RoundingMode.HALF_EVEN))
        return (if (h == "S" || h == "W") v.negate() else v).toDouble()
    }

    private fun n(s: String) = s.replace(",", "").trim().toDouble()

    private fun lon180(x: Double): Double { var l = x; while (l > 180) l -= 360; while (l <= -180) l += 360; return l }

    private fun csvRows(file: String): List<List<String>> = File("$dir/$file").readLines()
        .filter { it.isNotBlank() && !it.startsWith("#") }.drop(1).map { CrsCatalogCsv.splitCsv(it)!! }

    // ---- catalog content ----

    @Test fun `catalog lists all 953 NGS zones with methods, frames and beta status`() {
        assertTrue("problems ${load.problems}", load.problems.isEmpty())
        assertEquals(953, load.entries.size)
        assertEquals(mapOf("natrf2022" to 949, "patrf2022" to 2, "catrf2022" to 1, "matrf2022" to 1),
            load.entries.groupingBy { it.frameId }.eachCount())
        assertEquals(mapOf(ProjectionMethod.TRANSVERSE_MERCATOR to 423, ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP to 387,
            ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B to 143), load.entries.groupingBy { it.method!! }.eachCount())
        assertTrue(load.entries.all { it.declaredStatus == ProductStatus.VERIFIED_BETA && it.unit == CrsUnit.METRE })
        assertTrue(load.entries.all { it.dataset.contains("2026-05-14") })
        // Verified projections on NATRF2022 parse as operational; frame reachability is the registry's job.
        assertTrue(load.entries.filter { it.frameId == "natrf2022" }.all { it.operational && it.statusNote!!.contains("ngs_example_coordinates") })
        for (code in listOf("150001", "600001", "720001", "660001")) {
            val d = byCode.getValue(code)
            assertNull(d.frame)
            assertFalse(d.operational)
            assertEquals(ProductStatus.UNAVAILABLE, d.status)
            assertTrue(d.statusNote, d.statusNote!!.contains("frame ${d.frameId} is not defined in GeoKit yet"))
        }
    }

    @Test fun `catalog parameters equal the raw NGS zone definitions and envelopes`() {
        val defs = rawTable("zoneDefinitions.json")
        val bounds = rawTable("zoneBounds.json")
        assertEquals(byCode.keys, defs.keys)
        for ((code, z) in defs) {
            val d = byCode.getValue(code)
            val p = d.parameters
            assertEquals(code, z.getValue("Zone name"), d.name)
            assertEquals(code, z.getValue("Reference frame").lowercase(), d.frameId)
            val lonKey = if (d.method == ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B) "lonc" else "lon_0"
            assertEquals(code, dms(z.getValue("Origin latitude")), p.getValue("lat_0"), 1e-12)
            assertEquals(code, lon180(dms(z.getValue("Origin longitude east"))), p.getValue(lonKey), 1e-12)
            assertEquals(code, lon180(dms(z.getValue("Origin longitude west"))), p.getValue(lonKey), 1e-12)
            assertEquals(code, n(z.getValue("Projection origin scale")), p.getValue("k_0"), 0.0)
            assertEquals(code, n(z.getValue("False northing (m)")), p.getValue("y_0"), 0.0)
            assertEquals(code, n(z.getValue("False easting (m)")), p.getValue("x_0"), 0.0)
            // ift columns: metres / 0.3048 (NC 370001 rounded to 0.001 ift by NGS).
            assertEquals(code, n(z.getValue("False easting (ift)")), p.getValue("x_0") / 0.3048, 0.0011)
            val expected = when (z.getValue("Proj type")) {
                "TM" -> ProjectionMethod.TRANSVERSE_MERCATOR
                "LC1" -> ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP
                "OMC" -> ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B
                else -> error(code)
            }
            assertEquals(code, expected, d.method)
            if (expected == ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B) {
                assertEquals(code, n(z.getValue("Skew azimuth (deg)")), p.getValue("alpha"), 0.0)
                assertEquals(code, p.getValue("alpha"), p.getValue("gamma"), 0.0)   // rectified skew orthomorphic
            }
            val b = bounds.getValue(code)
            val a = d.areaOfUse
            assertEquals(code, lon180(n(b.getValue("Min lon east (deg)"))), a.west, 1e-9)
            assertEquals(code, lon180(n(b.getValue("Max lon east (deg)"))), a.east, 1e-9)
            assertEquals(code, n(b.getValue("Min lat (deg)")), a.south, 0.0)
            assertEquals(code, n(b.getValue("Max lat (deg)")), a.north, 0.0)
            assertTrue(code, d.aliases.contains(z.getValue("Zone abrv")))
        }
    }

    // ---- numerics ----

    @Test fun `GeoKit maths reproduces every NGS example point, forward and inverse`() {
        val rows = csvRows("ngs_example_coordinates.csv")
        assertEquals(953, rows.size)
        var worstFwd = 0.0
        var worstInvDeg = 0.0
        for (r in rows) {
            val d = byCode.getValue(r[0])
            val proj = d.method!!.create(d.parameters)   // also for zones whose frame is pending
            val lat = r[2].toDouble(); val lon = r[3].toDouble()
            val nM = r[5].toDouble(); val eM = r[6].toDouble()
            val (e, nn) = proj.forward(lat, lon)
            val err = max(abs(e - eM), abs(nn - nM))
            worstFwd = max(worstFwd, err)
            assertTrue("${r[0]} ${d.name}: forward off by $err m", err <= 0.0006)   // NGS rounds to 1 mm
            val (la, lo) = ProjectionMethod.inverse(proj, eM, nM)!!
            val inv = max(abs(la - lat), abs(lon180(lo - lon)))
            worstInvDeg = max(worstInvDeg, inv)
            assertTrue("${r[0]} ${d.name}: inverse off by $inv deg", inv <= 2e-8)
        }
        println("SPCS2022 vs NGS example points: worst forward ${"%.6f".format(worstFwd)} m, worst inverse ${"%.2e".format(worstInvDeg)} deg")
    }

    @Test fun `GeoKit maths matches PROJ at five points per zone and round-trips`() {
        val rows = csvRows("proj_vectors.csv")
        assertTrue(rows.size > 4000)
        val worst = HashMap<ProjectionMethod, Double>()
        for (r in rows) {
            val d = byCode.getValue(r[0])
            val proj = d.method!!.create(d.parameters)
            val lat = r[1].toDouble(); val lon = r[2].toDouble()
            val (e, nn) = proj.forward(lat, lon)
            val err = max(abs(e - r[3].toDouble()), abs(nn - r[4].toDouble()))
            worst.merge(d.method!!, err, ::max)
            assertTrue("${r[0]} ${d.name} at $lat,$lon: |GeoKit - PROJ| = $err m", err <= 1e-4)
            val (la, lo) = ProjectionMethod.inverse(proj, e, nn)!!
            assertTrue("${r[0]} round trip", abs(la - lat) < 1e-9 && abs(lon180(lo - lon)) < 1e-9)
        }
        println("SPCS2022 vs PROJ worst |dE|,|dN| by method: $worst")
    }

    @Test fun `representative zones match NGS - PA, OH, TX, CA, AK, HI, PR, Guam, Samoa`() {
        val rows = csvRows("ngs_example_coordinates.csv").associateBy { it[0] }
        val zones = mapOf(
            "420001" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // Pennsylvania statewide
            "421001" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // PA North East
            "421003" to ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B,     // PA Central
            "421004" to ProjectionMethod.TRANSVERSE_MERCATOR,           // PA West
            "390001" to ProjectionMethod.TRANSVERSE_MERCATOR,           // Ohio statewide
            "391025" to ProjectionMethod.TRANSVERSE_MERCATOR,           // Ohio Franklin
            "391048" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // Ohio Lucas
            "480001" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // Texas statewide
            "020001" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // Alaska statewide (crosses 180)
            "021001" to ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B,     // Alaska Southeast
            "021009" to ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B,     // Alaska Attu-Amchitka (east of 180)
            "150001" to ProjectionMethod.HOTINE_OBLIQUE_MERCATOR_B,     // Hawaii, PATRF2022
            "600001" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // American Samoa, PATRF2022, south
            "720001" to ProjectionMethod.LAMBERT_CONIC_CONFORMAL_1SP,   // Puerto Rico + USVI, CATRF2022
            "660001" to ProjectionMethod.TRANSVERSE_MERCATOR,           // Guam + CNMI, MATRF2022
        )
        for ((code, method) in zones) {
            val d = byCode.getValue(code)
            assertEquals(code, method, d.method)
            val r = rows.getValue(code)
            val (e, nn) = d.method!!.create(d.parameters).forward(r[2].toDouble(), r[3].toDouble())
            assertEquals("$code E", r[6].toDouble(), e, 0.0006)
            assertEquals("$code N", r[5].toDouble(), nn, 0.0006)
        }
        val ca = load.entries.first { it.name == "California" }
        val r = rows.getValue(ca.zoneCode!!)
        assertEquals(r[6].toDouble(), ca.method!!.create(ca.parameters).forward(r[2].toDouble(), r[3].toDouble()).first, 0.0006)
    }

