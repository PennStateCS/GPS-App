    // ---- registry: status, search, location ----

    /** TEST STUB: a registry where NATRF2022 is reachable (as after WP F), via an identity edge. Never production. */
    private val reachable: FrameTransformationRegistry = FrameTransformationRegistry(
        FrameTransformationRegistry.DEFAULT.registeredEdges + FrameEdge(
            ReferenceFrame.ITRF2020, ReferenceFrame.NATRF2022, "TEST STUB identity", null, "test only",
            { p, _ -> p }, { p, _ -> p },
        ),
        FrameTransformationRegistry.DEFAULT_UNAVAILABLE - ReferenceFrame.NATRF2022,
    )

    @Test fun `default registry - no SPCS2022 zone is operational, each says why`() {
        val r = CrsRegistry()
        val pa = r.byId("spcs2022:420001")
        assertTrue("$pa", pa is CrsLookup.Unsupported)
        pa as CrsLookup.Unsupported
        assertEquals("Pennsylvania", pa.definition!!.name)
        assertEquals(ProductStatus.UNAVAILABLE, pa.definition!!.status)
        assertTrue(pa.explanation, pa.explanation.contains("frame natrf2022 has no verified transformation"))
        val hi = r.byId("SPCS2022:150001") as CrsLookup.Unsupported
        assertTrue(hi.explanation, hi.explanation.contains("frame patrf2022 is not defined in GeoKit yet"))
        assertTrue(r.search("Pennsylvania", includeBeta = true).none { it.catalog == CrsCatalogId.SPCS2022 })
        assertEquals(5, r.search("Pennsylvania", CrsCatalogId.SPCS2022, includeNonOperational = true).size)
        assertTrue(r.atPosition(40.79, -77.86, CrsCatalogId.SPCS2022, includeBeta = true).isEmpty())
    }

    @Test fun `with a reachable frame, zones are VERIFIED_BETA and opt-in only`() {
        val r = CrsRegistry(frameRegistry = reachable)
        val c = r.catalog(CrsCatalogId.SPCS2022)
        assertEquals(949, c.operational.size)          // NATRF2022 zones; PATRF/CATRF/MATRF still pending
        val pa = (r.byId("spcs2022:420001") as CrsLookup.Found).definition
        assertEquals(ProductStatus.VERIFIED_BETA, pa.status)
        assertTrue(pa.isBeta)
        assertEquals("Pennsylvania (420001)", pa.label)
        // Not offered by default.
        assertTrue(r.search("PA_NE").isEmpty())
        assertTrue(r.atPosition(40.79, -77.86, CrsCatalogId.SPCS2022).isEmpty())
        // Opt-in: search by abbreviation (either form), name, code.
        assertEquals("421001", r.search("PA_NE", includeBeta = true).first().zoneCode)
        assertEquals("421001", r.search("pa ne", includeBeta = true).first().zoneCode)
        assertEquals("391025", r.search("391025", includeBeta = true).single().zoneCode)
        assertEquals(setOf("420001", "421001", "421002", "421003", "421004"),
            r.search("pennsylvania", CrsCatalogId.SPCS2022, includeBeta = true).map { it.zoneCode }.toSet())
        assertTrue(r.search("ohio", CrsCatalogId.SPCS2022, includeBeta = true, limit = 200).size > 80)
        // Forward / inverse through the registry equal NGS.
        val ngs = csvRows("ngs_example_coordinates.csv").first { it[0] == "420001" }
        val (e, nn) = pa.forward(ngs[2].toDouble(), ngs[3].toDouble())
        assertEquals(ngs[6].toDouble(), e, 0.0006)
        assertEquals(ngs[5].toDouble(), nn, 0.0006)
        val (la, lo) = pa.inverse(ngs[6].toDouble(), ngs[5].toDouble())
        assertEquals(ngs[2].toDouble(), la, 2e-8)
        assertEquals(ngs[3].toDouble(), lo, 2e-8)
        // SPCS83 untouched.
        assertEquals(ProductStatus.VERIFIED_LEGACY, (r.byEpsg(6562) as CrsLookup.Found).definition.status)
        assertTrue(r.byId("spcs2022:150001") is CrsLookup.Unsupported)
    }

    @Test fun `locate uses zone polygons and reports layered candidates, never one confident answer`() {
        val r = CrsRegistry(frameRegistry = reachable)
        // State College, PA: statewide + PA Central (multizone complete).
        val sc = r.locateSpcs2022(40.79, -77.86, includeBeta = true)
        assertEquals(CrsLocationBasis.ZONE_POLYGON, sc.basis)
        assertEquals(setOf("421003", "420001"), sc.candidates.map { it.zoneCode }.toSet())
        assertEquals("421003", sc.candidates.first().zoneCode)   // smaller zone first
        assertTrue(sc.isAmbiguous)
        // Columbus, OH (Franklin County): statewide + Franklin; not Pennsylvania.
        val col = r.locateSpcs2022(39.96, -83.0, includeBeta = true).candidates.map { it.zoneCode }
        assertTrue("$col", col.containsAll(listOf("390001", "391025")))
        assertTrue("$col", col.none { it!!.startsWith("42") })
        // The PA/OH state line (meridian 80 deg 31' W, here at 41.0 N): both states within the margin.
        val line = r.locateSpcs2022(41.0, -80.5194, includeBeta = true)
        val lineCodes = line.candidates.map { it.zoneCode!! }
        assertTrue("$line", line.nearBoundary)
        assertTrue("$lineCodes", lineCodes.any { it.startsWith("39") } && lineCodes.any { it.startsWith("42") })
        // Open Atlantic: nothing.
        assertEquals(CrsLocationBasis.NONE, r.locateSpcs2022(35.0, -50.0, includeBeta = true).basis)
        // Aleutians on both sides of 180 deg.
        assertTrue(r.locateSpcs2022(52.0, 179.0, includeBeta = true).candidates.any { it.zoneCode == "020001" })
        assertTrue(r.locateSpcs2022(51.9, -176.6, includeBeta = true).candidates.any { it.zoneCode == "020001" })
        // Offshore Gulf of Mexico: Gulf zones have no polygon in the NGS layers: envelopes only.
        val gulf = r.locateSpcs2022(27.34, -88.825, includeBeta = true)
        assertEquals(CrsLocationBasis.AREA_OF_USE_BOX, gulf.basis)
        assertTrue(gulf.candidates.any { it.zoneCode == "001001" })
        assertTrue(gulf.isAmbiguous)
        // Pending frames are listed only with includeNonOperational.
        assertTrue(r.locateSpcs2022(21.3, -157.85, includeBeta = true).candidates.isEmpty())
        assertEquals(listOf("150001"), r.locateSpcs2022(21.3, -157.85, includeNonOperational = true).candidates.map { it.zoneCode })
        // Without polygons the same point is located by envelopes and flagged as such.
        val boxes = CrsRegistry(frameRegistry = reachable, spcs2022BoundaryResource = null).locateSpcs2022(40.79, -77.86, includeBeta = true)
        assertEquals(CrsLocationBasis.AREA_OF_USE_BOX, boxes.basis)
        assertTrue(boxes.candidates.size >= 2 && boxes.isAmbiguous)
    }

