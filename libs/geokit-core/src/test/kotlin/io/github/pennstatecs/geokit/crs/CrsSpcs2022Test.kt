    @Test fun `v2 header - status and aliases columns, pending frames, unknown status`() {
        val h = CrsCatalogCsv.HEADER_V2
        val p = "lat_0=40;lon_0=-77;k_0=1;x_0=0;y_0=0"
        val r = CrsCatalogCsv.parse("""
            $h
            B1,,Beta,natrf2022,lcc1sp,$p,metre,-80,39,-74,42,d,v.csv,verified_beta,X_Y;Statewide
            B2,,Legacy default,nad83-2011,tm,$p,metre,-80,39,-74,42,d,v.csv,,
            B3,,Pending frame,catrf2022,lcc1sp,$p,metre,-80,39,-74,42,d,v.csv,verified_beta,
            B4,,Bad status,natrf2022,tm,$p,metre,-80,39,-74,42,d,v.csv,gold,
            B5,,Unavailable,natrf2022,tm,$p,metre,-80,39,-74,42,d,v.csv,unavailable,
            B6,,Unknown frame,xyz2022,tm,$p,metre,-80,39,-74,42,d,v.csv,verified_beta,
            B7,,Old column count,natrf2022,tm,$p,metre,-80,39,-74,42,d,v.csv
        """.trimIndent(), CrsCatalogId.SPCS2022)
        val by = r.entries.associateBy { it.zoneCode }
        assertEquals(listOf("B1", "B2", "B3", "B4", "B5"), r.entries.map { it.zoneCode })
        assertEquals(2, r.problems.size)
        assertEquals(ProductStatus.VERIFIED_BETA, by.getValue("B1").status)
        assertEquals(listOf("X_Y", "Statewide"), by.getValue("B1").aliases)
        assertEquals(ProductStatus.VERIFIED_LEGACY, by.getValue("B2").status)
        assertEquals(ReferenceFrame.NAD83_2011, by.getValue("B2").frame)
        assertNull(by.getValue("B3").frame)
        assertEquals("catrf2022", by.getValue("B3").frameId)
        assertEquals(ProductStatus.UNAVAILABLE, by.getValue("B3").status)
        assertTrue(by.getValue("B4").statusNote!!.contains("unknown status"))
        assertTrue(by.getValue("B5").statusNote!!.contains("unavailable"))
        // Version-1 files still load and default to VERIFIED_LEGACY.
        val v1 = CrsCatalogCsv.parse("${CrsCatalogCsv.HEADER}\nC1,,V1,nad83-2011,tm,$p,metre,-80,39,-74,42,d,v.csv\n", CrsCatalogId.SPCS2022)
        assertEquals(ProductStatus.VERIFIED_LEGACY, v1.entries.single().status)
    }
