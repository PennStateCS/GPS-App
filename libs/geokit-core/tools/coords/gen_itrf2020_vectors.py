"""Reference vectors for the ITRF2014 <-> ITRF2020 Helmert and ITRF2020 -> NAD83(2011).

Usage (from the repo root; Python 3.12, pyproj 3.8.0 / PROJ 9.8.1):

    python -I libs/geokit-core/tools/coords/gen_itrf2020_vectors.py \
        libs/geokit-core/src/test/resources/coords/itrf2020_vectors.csv

Writes one row per (operation, point, epoch):

    op,lat,lon,h,epoch,out_lat,out_lon,out_h

op is one of
  itrf2014_to_itrf2020   EPSG:7912 -> EPSG:9989  ("ITRF2014 to ITRF2020 (1)", position vector, t0 2015.0)
  itrf2020_to_itrf2014   EPSG:9989 -> EPSG:7912  (inverse of the same operation)
  itrf2020_to_nad83_2011 EPSG:9989 -> EPSG:6319  ("ITRF2020 to NAD83(2011) (1)", PROJ's direct EPSG
                         operation; geokit composes ITRF2020 -> ITRF2014 -> NAD83(2011) instead, which
                         agrees with it to well below 0.1 mm because the EPSG parameters of the direct
                         operation are the sum of the two edges, see FrameTransformationRegistryTest)

The script refuses to write anything if PROJ's best operation is not the expected EPSG operation or
is a ballpark (accuracy unknown) operation. Output is deterministic.
"""
import sys

import pyproj
from pyproj.transformer import TransformerGroup

EXPECTED = {
    "itrf2014_to_itrf2020": ("EPSG:7912", "EPSG:9989", "ITRF2014 to ITRF2020 (1)"),
    "itrf2020_to_itrf2014": ("EPSG:9989", "EPSG:7912", "Inverse of ITRF2014 to ITRF2020 (1)"),
    "itrf2020_to_nad83_2011": ("EPSG:9989", "EPSG:6319", "ITRF2020 to NAD83(2011) (1)"),
}

# (lat, lon, h): CONUS, Alaska, Hawaii, Puerto Rico, world, near the poles, both sides of the antimeridian.
POINTS = [
    (41.3477, -76.0226, 390.0),       # Pennsylvania
    (39.7392, -104.9903, 1609.0),     # Colorado
    (34.0522, -118.2437, 71.0),       # California
    (25.7617, -80.1918, -25.0),       # Florida (negative h)
    (47.6062, -122.3321, 0.0),        # Washington (h exactly 0)
    (61.2181, -149.9003, 40.0),       # Alaska, Anchorage
    (71.2906, -156.7887, 5.0),        # Alaska, Utqiagvik
    (51.8800, 176.6581, 30.0),        # Aleutians (east of the antimeridian)
    (19.8968, -155.5828, 4205.0),     # Hawaii, Mauna Kea
    (18.4655, -66.1057, 10.0),        # Puerto Rico
    (51.4779, -0.0015, 46.0),         # Greenwich
    (-33.8688, 151.2093, 58.0),       # Sydney
    (-22.9068, -43.1729, 11.0),       # Rio de Janeiro
    (35.6762, 139.6503, 40.0),        # Tokyo
    (0.0, 0.0, 0.0),                  # equator / prime meridian
    (89.9, 45.0, 2800.0),             # near the north pole
    (-89.9, -120.0, 2835.0),          # near the south pole
    (-16.5, 179.9999, 15.0),          # Fiji, west of the antimeridian
    (-16.5, -179.9999, 15.0),         # Fiji, east of the antimeridian
]

EPOCHS = [2010.0, 2015.0, 2020.0, 2026.9]


def transformer(op):
    src, dst, name = EXPECTED[op]
    group = TransformerGroup(src, dst, always_xy=True)
    if not group.best_available or not group.transformers:
        raise SystemExit(f"{op}: no available PROJ operation")
    t = group.transformers[0]
    if name not in t.description:
        raise SystemExit(f"{op}: unexpected PROJ operation {t.description!r}")
    if t.accuracy is None or t.accuracy < 0 or "ballpark" in t.description.lower():
        raise SystemExit(f"{op}: ballpark / unknown-accuracy operation {t.description!r}")
    return t


def main(out_path):
    rows = []
    for op in EXPECTED:
        t = transformer(op)
        for lat, lon, h in POINTS:
            for epoch in EPOCHS:
                x, y, z, _ = t.transform(lon, lat, h, epoch)
                rows.append(f"{op},{lat!r},{lon!r},{h!r},{epoch!r},{y:.12f},{x:.12f},{z:.6f}")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# Generated by gen_itrf2020_vectors.py with pyproj {pyproj.__version__} / PROJ {pyproj.proj_version_str}\n")
        f.write("op,lat,lon,h,epoch,out_lat,out_lon,out_h\n")
        f.write("\n".join(rows) + "\n")
    print(f"wrote {len(rows)} rows to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
