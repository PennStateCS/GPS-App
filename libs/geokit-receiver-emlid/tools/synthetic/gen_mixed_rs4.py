#!/usr/bin/env python3
"""Generates the SYNTHETIC mixed RS4 NMEA recordings used by EmlidSyntheticMixedStreamTest.

SYNTHETIC: not receiver output. Rates follow Emlid's documented RS4 defaults
(https://docs.emlid.com/reachrs4/specifications/nmea-format/, retrieved 2026-11-25):
GGA 5 Hz, ETC 5 Hz (same time tag as its GGA, sent right after it), RMC 1 Hz, GST 1 Hz.
Sentence shapes copy the RS4 captures in libs/geokit-gnss/src/test/resources/nmea/.

Usage (from the repo root):  python libs/geokit-receiver-emlid/tools/synthetic/gen_mixed_rs4.py
Writes into libs/geokit-receiver-emlid/src/test/resources/nmea/synthetic/. Deterministic.
"""
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "test", "resources", "nmea", "synthetic")


def cs(body):
    x = 0
    for c in body:
        x ^= ord(c)
    return "$%s*%02X" % (body, x)


def t(sec_of_day):
    cs_ = int(round(sec_of_day * 100))
    h, rem = divmod(cs_, 360000)
    m, rem = divmod(rem, 6000)
    s, c = divmod(rem, 100)
    return "%02d%02d%02d.%02d" % (h, m, s, c)


def gga(ts, i):
    lat = "4118.44%05d" % (42077 + i)
    return cs("GNGGA,%s,%s,N,07601.0311556,W,4,25,1.0,%.3f,M,-33.145,M,1.0,1116" % (t(ts), lat, 396.456 + i * 0.001))


def rmc(ts):
    return cs("GNRMC,%s,A,4118.4442077,N,07601.0311556,W,0.02,,251126,,,D" % t(ts))


def gst(ts, alt="0.016"):
    return cs("GNGST,%s,2.700,,,,0.010,0.010,%s" % (t(ts), alt))


def etc(ts, state):
    if state == "off":
        return cs("GNETC,%s,,,,,,,," % t(ts))
    if state == "setup":
        return cs("GNETC,%s,10,00,,,,,," % t(ts))
    if state == "align":
        return cs("GNETC,%s,20,00,,,,,," % t(ts))
    if state == "comp":
        return cs("GNETC,%s,30,00,268.660,116.146,17.651,6.280,6.280,6.991" % t(ts))
    if state == "comp_warn":
        return cs("GNETC,%s,30,10,268.660,116.146,17.651,6.280,6.280,6.991" % t(ts))
    raise ValueError(state)


START = 12 * 3600.0  # 12:00:00.00 UTC


def nominal():
    """10 s: tilt off 2 s, setup 1 s, alignment 2 s, compensating 5 s (last second with a motion warning)."""
    out = ["# SYNTHETIC RS4 mixed stream (not receiver output): GGA 5 Hz + ETC 5 Hz + RMC 1 Hz + GST 1 Hz.",
           "# Generated by libs/geokit-receiver-emlid/tools/synthetic/gen_mixed_rs4.py. Scenario: nominal."]
    for k in range(50):
        ts = START + k * 0.2
        sec = k // 5
        state = "off" if sec < 2 else "setup" if sec < 3 else "align" if sec < 5 else "comp_warn" if sec == 9 else "comp"
        if k % 5 == 0:
            out.append(rmc(ts))
        out.append(gga(ts, k))
        out.append(etc(ts, state))
        if k % 5 == 0:
            out.append(gst(ts))
    return out


def faults():
    """10 s of compensating epochs with faults (k = epoch index, 0.2 s apart):
    k=3: ETC dropped; k=6: ETC arrives BEFORE its GGA; k=8: ETC with a bad checksum;
    k=11: GGA dropped (its ETC still sent); k=13: GGA with a bad checksum (ETC fine);
    k=15..29: no ETC at all for 3 s (stale stream), then ETCs resume at k=30;
    k=20: RMC missing for that second; k=35: ETC carries the PREVIOUS epoch's time (late duplicate);
    k=40..: alignment again (bad GNSS), recovery to compensating at k=45.
    """
    out = ["# SYNTHETIC RS4 mixed stream (not receiver output): GGA 5 Hz + ETC 5 Hz + RMC 1 Hz + GST 1 Hz.",
           "# Generated by libs/geokit-receiver-emlid/tools/synthetic/gen_mixed_rs4.py. Scenario: faults (see generator)."]
    for k in range(50):
        ts = START + k * 0.2
        state = "align" if 40 <= k < 45 else "comp"
        if k % 5 == 0 and k != 20:
            out.append(rmc(ts))
        e = etc(ts, state)
        if k == 8:
            e = e[:-2] + ("00" if e[-2:] != "00" else "11")
        if k == 35:
            e = etc(ts - 0.2, state)
        g = gga(ts, k)
        if k == 13:
            g = g[:-2] + ("00" if g[-2:] != "00" else "11")
        if k == 6:
            out.append(e)
        if k != 11:
            out.append(g)
        if k not in (3, 6) and not (15 <= k < 30):
            out.append(e)
        if k % 5 == 0:
            out.append(gst(ts))
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, lines in (("SYNTHETIC_rs4_mixed_nominal.nmea", nominal()), ("SYNTHETIC_rs4_mixed_faults.nmea", faults())):
        with open(os.path.join(OUT, name), "w", newline="\n", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
