package io.github.pennstatecs.geokit.receiver.emlid.tilt

import io.github.pennstatecs.geokit.gnss.bus.adapters.NmeaFuser
import io.github.pennstatecs.geokit.gnss.model.Fix
import io.github.pennstatecs.geokit.gnss.model.Provider
import io.github.pennstatecs.geokit.gnss.nmea.parse.DefaultNmeaRegistry
import io.github.pennstatecs.geokit.gnss.nmea.sentence.GGA
import io.github.pennstatecs.geokit.gnss.nmea.sentence.GST
import io.github.pennstatecs.geokit.gnss.nmea.sentence.RMC
import io.github.pennstatecs.geokit.receiver.emlid.nmea.ETC
import io.github.pennstatecs.geokit.receiver.emlid.nmea.EmlidNmea
import io.github.pennstatecs.geokit.receiver.emlid.nmea.EtcFields
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * SYNTHETIC mixed RS4 streams (GGA 5 Hz + ETC 5 Hz + RMC 1 Hz + GST 1 Hz, Emlid's documented default rates),
 * generated by `tools/synthetic/gen_mixed_rs4.py` into `src/test/resources/nmea/synthetic/`. Not receiver
 * output: they exercise timestamp matching, buffering, out-of-order arrival, stale ETC, drops, recovery,
 * missing RMC and checksums through the unchanged registry, fuser and [EmlidTiltTracker].
 *
 * Receive times are simulated: the stream clock is the latest time tag seen so far (ms) plus 1 ms per line
 * within that epoch.
 */
class EmlidSyntheticMixedStreamTest {

    private data class Run(
        val fixes: List<Fix>,
        /** GGA time → association, in GGA order. */
        val assoc: List<Pair<String, EmlidTiltAssociation>>,
        val rejected: Int,
    )

    private fun run(name: String): Run {
        val lines = javaClass.getResourceAsStream("/nmea/synthetic/$name")!!.bufferedReader().readLines()
        assertTrue("header must say SYNTHETIC", lines.first().startsWith("# SYNTHETIC"))
        val registry = DefaultNmeaRegistry.create(verifyChecksum = true, requireChecksum = true, extraParsers = EmlidNmea.parsers)
        val fixes = mutableListOf<Fix>()
        val fuser = NmeaFuser(Provider.EXTERNAL_TCP,
            DefaultNmeaRegistry.create(verifyChecksum = true, requireChecksum = true, extraParsers = EmlidNmea.parsers),
            { fixes += it }, { }, clock = { 1_000L })   // constant non-zero clock: GST hold active, never times out
        val tracker = EmlidTiltTracker()
        val assoc = mutableListOf<Pair<String, EmlidTiltAssociation>>()
        var pending: Pair<GGA, Long>? = null
        var clockMs = 0L
        var rejected = 0
        var lineInEpoch = 0
        fun settle() { pending?.let { (g, at) -> assoc += g.timeRaw!! to tracker.associate(g, at) }; pending = null }
        lines.filter { it.startsWith("$") }.forEach { line ->
            fuser.accept(line)
            val s = registry.parse(line)
            if (s == null) { rejected++; return@forEach }
            val tag = when (s) { is GGA -> s.timeRaw; is ETC -> s.timeRaw; is RMC -> s.timeRaw; is GST -> s.timeRaw; else -> null }
            val before = clockMs
            EtcFields.parseTimeOfDay(tag)?.let { clockMs = maxOf(clockMs, Math.round(it * 1000)) }
            lineInEpoch = if (clockMs > before) 0 else lineInEpoch + 1
            val at = clockMs + lineInEpoch
            when (s) {
                is GGA -> { settle(); pending = s to at }   // associate after the epoch's ETC (it follows the GGA)
                is ETC -> tracker.onEtc(s, at)
                else -> Unit
            }
        }
        settle()
        fuser.flush()
        return Run(fixes, assoc, rejected)
    }

    private fun k(i: Int): String {
        val cs = 12 * 360000 + i * 20
        return "%02d%02d%02d.%02d".format(cs / 360000, cs / 6000 % 60, cs / 100 % 60, cs % 100)
    }

    @Test
    fun `SYNTHETIC nominal - every GGA pairs with its own ETC through the state sequence`() {
        val r = run("SYNTHETIC_rs4_mixed_nominal.nmea")
        assertEquals(0, r.rejected)
        assertEquals("one fix per GGA, though only every fifth GGA has an RMC/GST", 50, r.fixes.size)
        assertEquals(50, r.assoc.size)
        r.assoc.forEachIndexed { i, (time, a) ->
            assertEquals(k(i), time)
            assertEquals(time, TiltMatch.MATCHED, a.match)
            val sec = i / 5
            val expected = when {
                sec < 2 -> EmlidTiltState.OFF
                sec < 3 -> EmlidTiltState.INITIALIZING
                sec < 5 -> EmlidTiltState.ALIGNING
                else -> EmlidTiltState.ACTIVE
            }
            assertEquals(time, expected, a.state)
            assertEquals(time, sec == 9, a.reading!!.hasWarning)
        }
        // Fix times step by exactly 200 ms (GGA time + RMC date), in order.
        r.fixes.zipWithNext().forEach { (a, b) -> assertEquals(200L, b.timeUtc.toEpochMilli() - a.timeUtc.toEpochMilli()) }
        // GST (1 Hz) is used on its own epoch (from the second GST on: the fuser waits for GST only once it has seen one).
        for (i in 5 until 50 step 5) assertNotNull("vAcc at epoch $i", r.fixes[i].vAccM)
        // RMC (1 Hz) supplies speed on its own epochs.
        for (i in 0 until 50 step 5) assertNotNull("speed at epoch $i", r.fixes[i].speedMps)
    }

    @Test
    fun `SYNTHETIC faults - drops, out-of-order, stale stream, bad checksums and recovery`() {
        val r = run("SYNTHETIC_rs4_mixed_faults.nmea")
        assertEquals("one bad-checksum ETC (k=8) and one bad-checksum GGA (k=13)", 2, r.rejected)
        assertEquals("GGA k=11 dropped and k=13 rejected", 48, r.fixes.size)
        val byK = r.assoc.associate { it.first to it.second }
        assertEquals(48, byK.size)
        fun at(i: Int) = byK.getValue(k(i))
        for (i in 0 until 50) {
            if (i == 11 || i == 13) { assertTrue(k(i) !in byK); continue }
            val a = at(i)
            val expectedMatch = when (i) {
                3 -> TiltMatch.NOT_MATCHED          // ETC dropped
                8 -> TiltMatch.NOT_MATCHED          // ETC rejected by its checksum
                in 15..24 -> TiltMatch.NOT_MATCHED  // ETC missing, stream not yet stale (≤ 2 s since the last)
                in 25..29 -> TiltMatch.ETC_STREAM_STALE
                35 -> TiltMatch.NOT_MATCHED         // its ETC carried the previous epoch's time
                else -> TiltMatch.MATCHED           // incl. k=6 (ETC before GGA) and k=30 (recovery)
            }
            assertEquals("epoch $i", expectedMatch, a.match)
            val expectedState = when {
                expectedMatch != TiltMatch.MATCHED -> EmlidTiltState.UNKNOWN
                i in 40..44 -> EmlidTiltState.ALIGNING
                else -> EmlidTiltState.ACTIVE
            }
            assertEquals("epoch $i", expectedState, a.state)
        }
        // A missing RMC (second 4, k=20) never suppresses the GGA's fix.
        assertTrue(r.fixes.any { it.latDeg != 0.0 })
        assertEquals(48, r.fixes.map { it.timeUtc }.distinct().size)
    }
}
