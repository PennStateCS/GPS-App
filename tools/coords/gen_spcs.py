"""
Generate SpcsZones.kt (all official SPCS83 zones on NAD83(2011), from the PROJ/EPSG database)
and a test-vector CSV (PROJ forward results at points spread over each zone's area of use).

usage: gen_spcs.py <out_kotlin> <out_vectors_csv>
"""
import sys, re
from pyproj import CRS, Transformer
from pyproj.database import query_crs_info

out_kt, out_csv = sys.argv[1], sys.argv[2]

zones = []
for i in query_crs_info(auth_name="EPSG", pj_types=["PROJECTED_CRS"]):
    if not i.name.startswith("NAD83(2011) / ") or i.deprecated:
        continue
    crs = CRS.from_epsg(int(i.code))
    if crs.axis_info[0].unit_name != "metre":
        continue
    op = crs.coordinate_operation
    if not op.name.startswith("SPCS83"):
        continue
    code = int(op.to_json_dict()["id"]["code"])          # 1 SS M Z
    ss, m, z = (code // 100) % 100, (code // 10) % 10, code % 10
    fips = ss * 100 + (10 if m == 4 else 0) + z
    # Conversion codes that don't follow the 1·SS·M·Z pattern.
    if op.name.startswith("SPCS83 Alaska zone 10"):
        fips = 5010
    if op.name.startswith("SPCS83 Kentucky North"):   # EPSG conversion 15303
        fips = 1601
    p = {q.name: q.value for q in op.params}
    a = crs.area_of_use
    zones.append(dict(epsg=int(i.code), name=i.name[len("NAD83(2011) / "):], fips=fips,
                      method=op.method_name, p=p, bbox=(a.west, a.south, a.east, a.north), crs=crs))

zones.sort(key=lambda z: z["name"])
assert len({z["fips"] for z in zones}) == len(zones), "duplicate FIPS"

def k(v):  # Kotlin double literal, full precision
    return repr(float(v))

lines = []
for zn in zones:
    p = zn["p"]
    if zn["method"] == "Lambert Conic Conformal (2SP)":
        proj = (f"Lcc2({k(p['Latitude of false origin'])}, {k(p['Longitude of false origin'])}, "
                f"{k(p['Latitude of 1st standard parallel'])}, {k(p['Latitude of 2nd standard parallel'])}, "
                f"{k(p['Easting at false origin'])}, {k(p['Northing at false origin'])})")
    elif zn["method"] == "Transverse Mercator":
        proj = (f"Tm({k(p['Latitude of natural origin'])}, {k(p['Longitude of natural origin'])}, "
                f"{k(p['Scale factor at natural origin'])}, {k(p['False easting'])}, {k(p['False northing'])})")
    elif zn["method"] == "Hotine Oblique Mercator (variant A)":
        proj = (f"HomA({k(p['Latitude of projection centre'])}, {k(p['Longitude of projection centre'])}, "
                f"{k(p['Azimuth at projection centre'])}, {k(p['Angle from Rectified to Skew Grid'])}, "
                f"{k(p['Scale factor at projection centre'])}, {k(p['False easting'])}, {k(p['False northing'])})")
    else:
        raise SystemExit("unhandled method " + zn["method"])
    w, s, e, n = zn["bbox"]
    lines.append(f'        SpcsZone({zn["epsg"]}, {zn["fips"]}, "{zn["name"]}", {proj},\n'
                 f'            doubleArrayOf({k(w)}, {k(s)}, {k(e)}, {k(n)})),')

kt = f'''package app.surrealar.coords

// GENERATED by tools/coords/gen_spcs.py from the EPSG database shipped with PROJ {__import__("pyproj").proj_version_str}
// (pyproj {__import__("pyproj").__version__}). Do not edit by hand: regenerate instead.
//
// Every official SPCS83 zone on NAD83(2011) ({len(zones)} zones): the metre CRS of each zone, its NGS
// zone number, its defining conversion, and its EPSG area of use (W, S, E, N degrees).

internal object SpcsZoneTable {{
    val zones: List<SpcsZone> = listOf(
{chr(10).join(lines)}
    )
}}
'''
open(out_kt, "w", encoding="utf-8", newline="\n").write(kt)

# Test vectors: a 3x3 lattice inside each zone's area of use (inset 15%), forward via PROJ from
# NAD83(2011) geographic.
rows = ["epsg,lat,lon,easting,northing"]
for zn in zones:
    t = Transformer.from_crs(CRS.from_epsg(6318), zn["crs"], always_xy=True)
    w, s, e, n = zn["bbox"]
    if e < w:  # Aleutians cross the antimeridian (Alaska zone 10)
        e += 360
    for fy in (0.15, 0.5, 0.85):
        for fx in (0.15, 0.5, 0.85):
            lon = w + (e - w) * fx
            lon = lon - 360 if lon > 180 else lon
            lat = s + (n - s) * fy
            x, y = t.transform(lon, lat)
            rows.append(f'{zn["epsg"]},{lat!r},{lon!r},{x!r},{y!r}')
open(out_csv, "w", encoding="utf-8", newline="\n").write("\n".join(rows) + "\n")
print(len(zones), "zones;", len(rows) - 1, "vectors")
for zn in zones:
    if zn["name"].startswith(("California", "Texas", "Alaska", "New York Long", "Michigan", "Kentucky", "Puerto", "Florida", "Pennsylvania")):
        print(zn["fips"], zn["name"], zn["method"])
